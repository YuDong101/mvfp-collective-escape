function run_core_b(root)
addpath(fullfile(root,'function'));addpath(fullfile(root,'recompute'));
set(0,'DefaultFigureVisible','off');maxNumCompThreads(1);
base=mvfp_paper_revision_config(root);
data=fullfile(root,'outputs','pairwise_paper_revision_v2');
folder=fullfile(data,'second_batch','local_spectrum');if ~isfolder(folder),mkdir(folder);end
spectra=cell(1,4);gridN=[201 1001 2001 4001];
for k=1:4
    file=fullfile(folder,sprintf('spectrum_Nx%d.mat',gridN(k)));
    if isfile(file),q=load(file,'s');s=q.s;else
        s=compute_mvfp_revision_local_spectrum(base.parB,struct('Nx',gridN(k),'runGrowth',gridN(k)==1001));
        save(file,'s','-v7.3');
    end
    assert(s.positiveModeVerified);spectra{k}=s;
    fprintf('Fresh spectrum Nx=%d lambda=%.15g\n',gridN(k),s.lambda);
end
cfg=struct('projectRoot',root,'outputDir',fullfile(data,'second_batch','basin_B_local'), ...
    'gridN',[2001 4001],'coarseP0',[.06 .07 .075 .08],'seedP0',.071, ...
    'generalBracketWidth',6e-7,'fineBracketWidth',6e-7, ...
    'stageBudgetSeconds',86400,'maxCaseSeconds',7200,'reuseCheckpointDirs',{{}});
basin=compute_mvfp_revision_basin(base.parB,cfg);
assert(~basin.stoppedAtBudget && numel(basin.brackets)==2 && all([basin.brackets.isTargetMet]));
b=basin.brackets(1);PbInterval=[b.lowerP0 b.upperP0];
fine=basin.brackets(2);basinUncertainty=max(1e-6,max(abs([fine.lowerP0 fine.upperP0]-mean(PbInterval))));
lambdaUncertainty=max(1e-6,abs(spectra{4}.lambda-spectra{3}.lambda));
folder=fullfile(data,'third_batch','residence_feasibility');if ~isfolder(folder),mkdir(folder);end
cfg=struct('spectrumFile',fullfile(data,'second_batch','local_spectrum','spectrum_Nx2001.mat'), ...
    'basinFile',fullfile(data,'second_batch','basin_B_local','basin_B_results.mat'), ...
    'uncertaintyFile',fullfile(folder,'empirical_uncertainty.mat'), ...
    'PbInterval',PbInterval,'PbGridN',2001,'basinUncertainty',basinUncertainty, ...
    'lambdaUncertainty',lambdaUncertainty,'deltaMin',10*basinUncertainty,'T',200,'traceStep',.1, ...
    'stageBudgetSeconds',86400,'maxCaseSeconds',7200,'outputFile',fullfile(folder,'residence_prediction.mat'));
uncertainty=struct('spectrumHash',mvfp_streaming_sha256(cfg.spectrumFile), ...
    'basinHash',mvfp_streaming_sha256(cfg.basinFile),'PbInterval',PbInterval, ...
    'basinUncertainty',basinUncertainty,'lambdaUncertainty',lambdaUncertainty, ...
    'status','empirical-spatial-refinement-allowance-not-a-rigorous-error-bound', ...
    'method','Fresh Nx2001/Nx4001 basin brackets and spectrum difference; minimum allowance 1e-6; no old fitted output used.');
save(cfg.uncertaintyFile,'uncertainty');
out=compute_mvfp_revision_residence(cfg);
if isfield(out,'prediction'),writetable(out.prediction.table,fullfile(folder,'residence_prediction.csv'));end
assert(isfield(out,'prediction'),'Residence calculation incomplete');
solver=base.mvfp;solver.xGridN=2001;solver.fluxScheme='exponential-fit';solver.odeRelTol=1e-8;solver.odeAbsTol=1e-12;
cfg=struct('projectRoot',root,'outputDir',fullfile(data,'third_batch','B_time_boundary'), ...
    'par',base.parB,'mvfp',solver,'times',[50 55 60 65 70 75], ...
    'P0Values',mean(PbInterval)+1e-5*[1 2 4 8 16 32], ...
    'outputTimeStep',.1,'bracketWidth',1e-6,'maxStageSeconds',86400,'maxCaseSeconds',7200);
boundary=compute_mvfp_revision_time_windows(cfg);
save(fullfile(root,'data','core_b_summary.mat'),'PbInterval','basinUncertainty','lambdaUncertainty','boundary','-v7.3');
fid=fopen(fullfile(root,'logs','core_b_complete.json'),'w');
fwrite(fid,jsonencode(struct('status','computed-awaiting-audit','PbInterval',PbInterval,'lambda',spectra{3}.lambda, ...
    'finishedAt',char(datetime('now')))));fclose(fid);
end
